// Difficulty report for the exams: text measures per exam and the exams that stand out.
// Writes docs/reports/exam-difficulty.md. The measures are rough signals, not a CEFR level.
// Usage: node scripts/exam-difficulty.mjs [--stdout]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  examTexts,
  knownWords,
  mean,
  measureTexts,
  outliers,
  standardDeviation,
} from './lib/difficulty.mjs';
import { listExamFiles, readExam } from './lib/exam-files.mjs';

const read = (path) => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'));
const known = knownWords(
  read('../src/assets/vocabulary/b1-preliminary.json'),
  read('../src/assets/grammar/irregular-verbs.json'),
);
const target = fileURLToPath(new URL('../docs/reports/exam-difficulty.md', import.meta.url));

const rows = listExamFiles()
  .map((entry) => readExam(entry))
  .filter((exam) => exam.level === 'B1')
  .map((exam) => {
    const texts = examTexts(exam);
    return {
      id: exam.id,
      title: exam.title,
      reading: measureTexts(texts.reading, known),
      listening: measureTexts(texts.listening, known),
    };
  })
  .sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true }));

/** One number per exam: the mean z-score of the measures where higher means harder. */
const METRICS = [
  ['reading', 'wordsPerSentence', 1],
  ['reading', 'flesch', -1],
  ['reading', 'offListPercent', 1],
  ['listening', 'wordsPerSentence', 1],
  ['listening', 'flesch', -1],
  ['listening', 'offListPercent', 1],
];
const zScores = METRICS.map(([skill, key, sign]) => {
  const values = rows.map((r) => r[skill][key]);
  const m = mean(values);
  const sd = standardDeviation(values) || 1;
  return values.map((v) => (sign * (v - m)) / sd);
});
rows.forEach((row, i) => {
  row.score = Math.round((mean(zScores.map((z) => z[i])) + Number.EPSILON) * 100) / 100;
});

const LABELS = {
  wordsPerSentence: 'words per sentence',
  flesch: 'reading ease',
  offListPercent: '% words not in the B1 list',
};
const fmt = (n) => (Number.isInteger(n) ? String(n) : n.toFixed(1));
const stat = (skill, key) => {
  const values = rows.map((r) => r[skill][key]);
  return `${fmt(mean(values))} (${fmt(Math.min(...values))} to ${fmt(Math.max(...values))})`;
};

const flagged = [];
for (const [skill, key, sign] of METRICS) {
  const values = rows.map((r) => r[skill][key]);
  for (const { index, z } of outliers(values)) {
    const harder = sign * z > 0;
    flagged.push({
      id: rows[index].id,
      line: `${rows[index].id} (${rows[index].title}): ${skill} ${LABELS[key]} ${fmt(values[index])}, ${harder ? 'harder' : 'easier'} than the others (z ${z > 0 ? '+' : ''}${z})`,
    });
  }
}
const byScore = [...rows].sort((a, b) => b.score - a.score);
const offListAll = new Map();
for (const row of rows)
  for (const w of [...row.reading.offListWords, ...row.listening.offListWords])
    offListAll.set(w, (offListAll.get(w) ?? 0) + 1);
const commonOffList = [...offListAll]
  .filter(([, n]) => n >= 5)
  .sort((a, b) => b[1] - a[1])
  .slice(0, 40);

const lines = [
  '# Exam difficulty report',
  '',
  `Generated by \`npm run exams:difficulty\` for ${rows.length} B1 exams. Do not edit by hand.`,
  '',
  '## How to read it',
  '',
  '- **Words per sentence**: longer sentences are harder to follow.',
  '- **Reading ease** (Flesch): higher is easier. Short words and short sentences give a high value.',
  '- **Not in the B1 list**: share of words (names left out) whose base form is not in the Cambridge B1 Preliminary vocabulary list. Topic words, compounds and some regular forms count here too, so the value is never zero. `src/assets/vocabulary/b1-preliminary.json` also misses some headwords of the official list (for example all words that start with "al", and "week"), so compare the exams with each other, not with zero.',
  '- **Score**: the mean z-score of the six measures, with the sign set so that a higher score means a harder exam. 0 is the average exam.',
  '',
  'These are rough signals for review, not a CEFR level. An outlier is an exam to read again, not a mistake.',
  '',
  '## Averages and ranges',
  '',
  '| Measure | Reading | Listening |',
  '| --- | --- | --- |',
  `| Words | ${stat('reading', 'words')} | ${stat('listening', 'words')} |`,
  `| Words per sentence | ${stat('reading', 'wordsPerSentence')} | ${stat('listening', 'wordsPerSentence')} |`,
  `| Reading ease | ${stat('reading', 'flesch')} | ${stat('listening', 'flesch')} |`,
  `| % not in the B1 list | ${stat('reading', 'offListPercent')} | ${stat('listening', 'offListPercent')} |`,
  '',
  '## Outliers (more than two standard deviations from the mean)',
  '',
  ...(flagged.length ? flagged.map((f) => `- ${f.line}`) : ['None.']),
  '',
  '## Hardest and easiest exams by score',
  '',
  '| Hardest | Score | Easiest | Score |',
  '| --- | --- | --- | --- |',
  ...byScore.slice(0, 8).map((r, i) => {
    const e = byScore[byScore.length - 1 - i];
    return `| ${r.id} ${r.title} | ${r.score} | ${e.id} ${e.title} | ${e.score} |`;
  }),
  '',
  '## Words outside the B1 list used in five or more exams',
  '',
  commonOffList.map(([w, n]) => `${w} (${n})`).join(', ') || 'None.',
  '',
  '## All exams',
  '',
  '| Exam | R words | R w/s | R ease | R off-list % | L words | L w/s | L ease | L off-list % | Score |',
  '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ...rows.map(
    (r) =>
      `| ${r.id} | ${r.reading.words} | ${fmt(r.reading.wordsPerSentence)} | ${fmt(r.reading.flesch)} | ${fmt(r.reading.offListPercent)} | ${r.listening.words} | ${fmt(r.listening.wordsPerSentence)} | ${fmt(r.listening.flesch)} | ${fmt(r.listening.offListPercent)} | ${r.score} |`,
  ),
  '',
];

const report = lines.join('\n');
if (process.argv.includes('--stdout')) {
  console.log(report);
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, report);
  console.log(`Wrote ${target}`);
  console.log(
    `${flagged.length} outlier measure(s) in ${new Set(flagged.map((f) => f.id)).size} exam(s).`,
  );
}
